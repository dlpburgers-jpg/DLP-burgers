import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import {parse} from 'acorn';
import {transformSync} from 'rolldown/utils';
const root='release-static',old='assets/app-stamps-6478210d7383.js',oldCss='assets/stamps-e95cbe3dd3bb.css';
const hash=b=>createHash('sha256').update(b).digest('hex');
let app=readFileSync(join(root,old),'utf8');
if(hash(app)!=='6478210d73839396e17f90164e2cb53163a10ca2d1f5872ebc987e0671246c67')throw Error('Wrong reviewed base');
const raw=readFileSync('src/components/LoyaltyStamps.jsx','utf8').replace(/^import .*;\r?\n/gm,'').replace('export default ','');
const compiled=transformSync('LoyaltyStamps.jsx',raw,{jsx:{runtime:'classic',pragma:'m.createElement',pragmaFrag:'m.Fragment'}});
if(compiled.errors.length)throw Error(JSON.stringify(compiled.errors));
const ast=parse(app,{ecmaVersion:'latest',sourceType:'module'});
const target=ast.body.find(n=>n.declarations?.some(d=>d.id?.name==='DlpLoyaltyStamps'));
if(!target||target.declarations.length!==1)throw Error('Unexpected component declaration');
app=app.slice(0,target.start)+'const DlpLoyaltyStamps=(()=>{const {useState,useRef}=m;const rpc=Q;const {stampRewards,stampProducts}=DlpStamp;'+compiled.code+';return LoyaltyStamps})();'+app.slice(target.end);
parse(app,{ecmaVersion:'latest',sourceType:'module'});
const asset='assets/app-stamps-'+hash(app).slice(0,12)+'.js';
const css=readFileSync('src/components/LoyaltyStamps.css','utf8'),cssAsset='assets/stamps-'+hash(css).slice(0,12)+'.css';
let html=readFileSync(join(root,'index.html'),'utf8'),sw=readFileSync(join(root,'sw.js'),'utf8');
if(!html.includes(old)||!html.includes(oldCss)||!sw.includes(old)||!sw.includes(oldCss))throw Error('Wrong HTML or worker');
html=html.replace(old,asset).replace(oldCss,cssAsset);
sw=sw.replace(old,asset).replace(oldCss,cssAsset).replace(/const CACHE = 'dlp-v5-[a-f0-9]+';/,"const CACHE = 'dlp-v5-"+hash(app+html+css).slice(0,12)+"';");
writeFileSync(join(root,asset),app);writeFileSync(join(root,cssAsset),css);writeFileSync(join(root,'index.html'),html);writeFileSync(join(root,'sw.js'),sw);
const walk=(d,p='')=>readdirSync(d,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(join(d,e.name),p+e.name+'/'):[p+e.name]);
writeFileSync('docs/release-static-sha256.json',JSON.stringify(Object.fromEntries(walk(root).sort().map(p=>[p,hash(readFileSync(join(root,p)))])),null,2)+'\n');
writeFileSync('scripts/build-reviewed-release.mjs',readFileSync('scripts/build-reviewed-release.mjs','utf8').replace(old.split('/')[1],asset.split('/')[1]));
console.log(JSON.stringify({asset,cssAsset,sha256:hash(app)}));
